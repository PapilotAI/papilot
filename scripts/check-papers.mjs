import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Fastify from 'fastify';
import staticFiles from '@fastify/static';
import { chromium } from '../vendor/latex-review/node_modules/playwright/index.mjs';
const server = Fastify();
await server.register(staticFiles, { root: path.resolve('dist') });
await server.listen({ host: '127.0.0.1', port: 0 });
const browser = await chromium.launch({ channel: process.env.PAPILOT_BROWSER_CHANNEL || 'chrome', headless: true });
const projects = [{ id: 'alpha', name: 'Alpha paper', path: '/papers/alpha', createdAt: 1 }, { id: 'beta', name: 'Beta paper', path: '/papers/beta', createdAt: 2 }];
const state = { version: '0.6.0', csrf: 'fixture', projects: structuredClone(projects), tasks: [], requests: [], runtime: { connected: true, authenticated: false, account: null, error: null, models: [] }, viewer: { id: 'owner', role: 'owner', name: 'Owner', listener: 'local', owner: 'Owner' } };
const git = { branch: 'main', upstream: null, ahead: 0, behind: 0, files: [], head: null };
const requests = [], errors = [];
fs.mkdirSync('test-results', { recursive: true });
try {
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 800 } });
  await context.route('**/api/**', route => {
    const url = new URL(route.request().url()), match = url.pathname.match(/^\/api\/projects\/([^/]+)\/(rename|path|remove)$/);
    if (match && route.request().method() === 'POST') {
      const [, id, action] = match, body = route.request().postDataJSON(), paper = state.projects.find(p => p.id === id);
      requests.push({ id, action, body });
      if (action === 'path' && body.path === '/missing') return route.fulfill({ status: 400, json: { error: 'Repository not found.' } });
      if (action === 'remove') state.projects = state.projects.filter(p => p.id !== id);
      else Object.assign(paper, body);
      return route.fulfill({ json: paper || { ok: true } });
    }
    if (url.pathname === '/api/state') return route.fulfill({ json: state });
    if (url.pathname === '/api/updates') return route.fulfill({ json: { currentVersion: state.version, latestVersion: state.version, phase: 'idle' } });
    if (url.pathname === '/api/events') return route.fulfill({ contentType: 'text/event-stream', body: ': fixture\n\n' });
    if (url.pathname.endsWith('/skills')) return route.fulfill({ json: { skills: [] } });
    if (url.pathname.endsWith('/manuscript')) return route.fulfill({ json: { git, build: { status: 'failed', error: 'Fixture preview' }, annotations: [] } });
    if (url.pathname.endsWith('/git')) return route.fulfill({ json: git });
    return route.fulfill({ json: {} });
  });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.server.address().port}`);
  const switcher = page.getByRole('button', { name: 'Paper: Alpha paper', exact: true });
  async function edit(name) { await switcher.click(); await page.getByRole('menuitem', { name: `Edit ${name}`, exact: true }).click(); }
  await switcher.click(); await page.getByRole('menuitemradio', { name: 'Beta paper', exact: true }).waitFor();
  assert.equal(await page.locator('.paper-menu [aria-haspopup="menu"]').count(), 0, 'Paper edits have no submenu');
  await page.locator('.paper-menu').screenshot({ path: 'test-results/paper-menu.png', animations: 'disabled' });
  const betaEdit = page.getByRole('menuitem', { name: 'Edit Beta paper', exact: true });
  await betaEdit.focus(); await page.keyboard.press('Enter');
  let dialog = page.getByRole('dialog', { name: 'Edit paper', exact: true }); await dialog.waitFor();
  const name = page.getByRole('textbox', { name: 'Paper name', exact: true }), repo = page.getByRole('textbox', { name: 'Repository path', exact: true });
  assert.equal(await name.inputValue(), 'Beta paper'); assert.equal(await repo.inputValue(), '/papers/beta');
  await page.screenshot({ path: 'test-results/paper-edit.png', animations: 'disabled' });
  await name.fill('Cancelled'); await name.press('Escape');
  assert.equal(requests.length, 0); assert.ok(await switcher.evaluate(el => el === document.activeElement));
  await edit('Beta paper'); await name.fill('  Better   paper '); await name.press('Enter');
  await dialog.waitFor({ state: 'hidden' });
  assert.deepEqual(requests.at(-1), { id: 'beta', action: 'rename', body: { name: 'Better paper' } }); assert.ok(await switcher.isVisible());
  await edit('Better paper'); await name.fill('Relocated paper'); await repo.fill('/missing'); await repo.press('Enter');
  await page.getByRole('alert').filter({ hasText: 'Repository not found.' }).waitFor();
  assert.equal(state.projects.find(p => p.id === 'beta').path, '/papers/beta');
  assert.equal(state.projects.find(p => p.id === 'beta').name, 'Better paper');
  await repo.fill('/papers/relocated'); await repo.press('Enter'); await dialog.waitFor({ state: 'hidden' });
  assert.deepEqual(requests.at(-1), { id: 'beta', action: 'path', body: { name: 'Relocated paper', path: '/papers/relocated' } }); assert.ok(await switcher.isVisible());
  await page.setViewportSize({ width: 320, height: 640 }); await page.getByRole('button', { name: 'Show task list', exact: true }).click();
  await edit('Relocated paper'); await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: 'test-results/paper-edit-mobile.png', animations: 'disabled' });
  const saveBounds = await dialog.getByRole('button', { name: 'Save', exact: true }).boundingBox(), removeBounds = await dialog.getByRole('button', { name: 'Remove paper', exact: true }).boundingBox();
  assert.ok(Math.abs(saveBounds.y - removeBounds.y) < 2, 'Mobile editor actions fit in one row');
  await name.fill('Unsaved draft');
  await dialog.getByRole('button', { name: 'Remove paper', exact: true }).click();
  const confirmation = page.getByRole('dialog', { name: 'Remove paper?', exact: true }); await confirmation.waitFor();
  await confirmation.getByText('Files on disk, Git history and task worktrees will stay in place.').waitFor();
  assert.equal(await confirmation.getByRole('button', { name: 'Cancel', exact: true }).evaluate(el => el === document.activeElement), true);
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await name.inputValue(), 'Unsaved draft'); assert.equal(state.projects.length, 2);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 800 }); await page.emulateMedia({ colorScheme: 'light' });
  await edit('Relocated paper'); await dialog.getByRole('button', { name: 'Remove paper', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Remove from Papilot', exact: true }).click(); await confirmation.waitFor({ state: 'hidden' });
  assert.deepEqual(state.projects.map(p => p.id), ['alpha']); assert.ok(await switcher.isVisible());
  await edit('Alpha paper'); await dialog.getByRole('button', { name: 'Remove paper', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Remove from Papilot', exact: true }).click(); await confirmation.waitFor({ state: 'hidden' });
  await page.getByRole('heading', { name: 'Add your first paper', exact: true }).waitFor();
  state.projects = structuredClone(projects); state.viewer.role = 'member'; state.viewer.listener = 'account';
  await page.reload(); await edit('Beta paper');
  assert.equal(await name.isEnabled(), true); assert.equal(await repo.isDisabled(), true);
  assert.equal(await dialog.getByRole('button', { name: 'Remove paper', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: Pencil opens one paper editor, both fields save together, failed saves are atomic, removal stays in the dialog, mobile and owner-only controls');
} finally { await browser.close(); await server.close(); }
