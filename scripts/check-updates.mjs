import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Fastify from 'fastify';
import staticFiles from '@fastify/static';
import { chromium } from '../vendor/latex-review/node_modules/playwright/index.mjs';

const server = Fastify();
await server.register(staticFiles, { root: path.resolve('dist') });
await server.listen({ host: '127.0.0.1', port: 0 });
const origin = `http://127.0.0.1:${server.server.address().port}`;
const browser = await chromium.launch({ channel: process.env.PAPILOT_BROWSER_CHANNEL || 'chrome', headless: true });
const state = { version: '0.6.0', csrf: 'fixture', projects: [], tasks: [], requests: [], runtime: { connected: true, authenticated: false, account: null, error: null, models: [] }, viewer: { id: 'owner', name: 'Owner', role: 'owner', listener: 'local', owner: 'Owner' } };
let update = { currentVersion: '0.6.0', latestVersion: '0.6.0', phase: 'idle', checkedAt: Date.now(), error: null, canUpdate: true }, offline = false;
const installs = [], errors = [];
fs.mkdirSync('test-results', { recursive: true });
try {
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1440, height: 900 } });
  await context.route('**/api/**', route => {
    const pathname = new URL(route.request().url()).pathname;
    if (pathname === '/api/state') return route.fulfill({ json: state });
    if (pathname === '/api/updates') return offline ? route.abort() : route.fulfill({ json: update });
    if (pathname === '/api/updates/install') { installs.push(route.request().postDataJSON()); update.phase = 'installing'; return route.fulfill({ json: update }); }
    if (pathname === '/api/events') return route.fulfill({ contentType: 'text/event-stream', body: ': fixture\n\n' });
    return route.fulfill({ json: {} });
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin); await page.getByRole('button', { name: '设置', exact: true }).waitFor();
  assert.equal(await page.locator('.update-badge').count(), 0, 'Up-to-date installations do not show an update badge');
  update = { ...update, latestVersion: '0.7.0', phase: 'available' };
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  const badge = page.locator('.update-badge'); await badge.waitFor();
  const settings = await page.getByRole('button', { name: '设置', exact: true }).boundingBox(), tag = await badge.boundingBox();
  assert.ok(tag.y + tag.height <= settings.y, 'Update notices sit above the brand and Settings row');
  await page.locator('.sidebar-footer').screenshot({ path: 'test-results/update-badge.png' });
  await badge.click();
  const dialog = page.getByRole('dialog', { name: '更新 Papilot', exact: true }); await dialog.waitFor();
  await page.screenshot({ path: 'test-results/update-dialog.png' });
  await dialog.getByRole('button', { name: '稍后', exact: true }).click(); assert.equal(installs.length, 0);
  assert.ok(await badge.evaluate(element => element === document.activeElement));
  await badge.click(); await dialog.getByRole('button', { name: '更新到 0.7.0', exact: true }).click();
  await dialog.getByText('正在下载并检查新版本…', { exact: true }).waitFor();
  assert.deepEqual(installs, [{ version: '0.7.0' }]);
  assert.equal(await dialog.getByRole('button', { name: '更新到 0.7.0', exact: true }).count(), 0);
  update.phase = 'waiting'; await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await dialog.getByText('更新已就绪，将在任务和 PDF 编译完成后重启。', { exact: true }).waitFor();
  update.phase = 'failed'; update.error = 'Startup check failed.';
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await dialog.getByRole('button', { name: '重试更新', exact: true }).click();
  assert.equal(installs.length, 2);
  update.phase = 'restarting'; update.error = null;
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await dialog.getByText('正在重启 Papilot，页面将自动重连，草稿会保留。', { exact: true }).waitFor();
  offline = true; await page.evaluate(() => window.dispatchEvent(new Event('online')));
  assert.ok(await dialog.isVisible(), 'The update panel survives a disconnected restart');
  await page.evaluate(() => localStorage.setItem('papilot:update-test-draft', 'keep this draft'));
  offline = false; update.phase = 'updated'; update.currentVersion = state.version = '0.7.0';
  await Promise.all([page.waitForNavigation(), page.evaluate(() => window.dispatchEvent(new Event('online')))]);
  assert.equal(await page.evaluate(() => localStorage.getItem('papilot:update-test-draft')), 'keep this draft');
  await page.getByRole('button', { name: '设置', exact: true }).waitFor();
  assert.equal(await page.locator('.update-badge').count(), 0);
  update = { ...update, latestVersion: '0.8.0', phase: 'available' };
  await page.evaluate(() => window.dispatchEvent(new Event('online'))); await badge.waitFor();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.locator('.sidebar-footer').screenshot({ path: 'test-results/update-badge-dark.png' });
  await page.setViewportSize({ width: 320, height: 640 });
  await page.getByRole('button', { name: '显示任务列表', exact: true }).click();
  await badge.waitFor(); await badge.click(); await dialog.waitFor();
  assert.ok((await dialog.boundingBox()).width <= 320);
  await page.screenshot({ path: 'test-results/update-dialog-mobile.png', animations: 'disabled' });
  state.viewer.role = 'member'; state.viewer.listener = 'account';
  await page.reload();
  await page.getByRole('heading', { name: '还没有论文', exact: true }).waitFor();
  assert.equal(await page.locator('.update-badge').count(), 0, 'Collaborators have no update action');
  assert.deepEqual(errors, []);
  console.log('PASS: Update discovery, compact badge, confirmation, progress, retry, automatic reconnect/reload, dark/mobile layout and owner-only UI');
} finally { await browser.close(); await server.close(); }
